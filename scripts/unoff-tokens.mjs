/**
 * Writes the @unoff/ui spinner glyph alone (src/styles/generated/unoff-spinner.css)
 * for the reveal motion: the rest of the library's icon set is not shipped
 * (the site uses Lucide).
 *
 * Runs before `dev` and `build`; re-run after updating @unoff/ui.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkgDir = join(root, 'node_modules/@unoff/ui')
const { version } = JSON.parse(
  readFileSync(join(pkgDir, 'package.json'), 'utf8')
)

const icons = readFileSync(
  join(pkgDir, 'dist/assets/styles/icons/styles/yelbolt.css'),
  'utf8'
)
const spinner = icons.match(/--icon-spinner:\s*(url\("[^"]*"\))/)
if (!spinner) throw new Error('No --icon-spinner in the Yelbolt icon set')

const out = join(root, 'src/styles/generated')
mkdirSync(out, { recursive: true })
writeFileSync(
  join(out, 'unoff-spinner.css'),
  `/* Generated by scripts/unoff-tokens.mjs from @unoff/ui ${version}. Do not edit. */\n` +
    `:root {\n  --icon-spinner: ${spinner[1]};\n}\n`
)
console.log('unoff tokens: spinner → src/styles/generated/unoff-spinner.css')
